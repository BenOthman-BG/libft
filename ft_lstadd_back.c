#include "libft.h"

void	ft_lstadd_back(t_list **lst, t_list *new)
{
	t_list	*p;

	if (lst == NULL || new == NULL)
		return ;
	p = ft_lstlast(*lst);
	if (p == NULL)
		*lst = new;
	else
		p->next = new;
}
